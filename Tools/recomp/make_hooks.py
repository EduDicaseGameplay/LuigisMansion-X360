#!/usr/bin/env python3
"""Write Tools/recomp/hooks.txt: the European functions that get a host (HLE) body.

Every function the symbol matcher placed in a Dolphin SDK unit that drives hardware (OS kernel,
GX, VI, PAD, DVD, AR/ARQ, AI, DSP, CARD, SI, EXI, debugger) is hooked; the translated body of a
hook never runs. Pure-computation SDK units stay recompiled (OSAlloc, OSArena, Padclamp, mtx).
Extra lines from Tools/recomp/hooks_extra.txt (game hooks) are appended.

Usage: make_hooks.py <GLMP01_names.txt> <hooks.txt>
"""
import os
import sys

HLE_PREFIXES = ("os/", "gx/", "vi/", "pad/", "dvd/", "ar/", "card/", "ai/", "dsp/", "db/", "si/", "exi/",
                "TRK_MINNOW_DOLPHIN/", "OdemuExi2/", "amcstubs/", "odenotstub/")
RECOMPILE = ("os/OSAlloc.c", "os/OSArena.c", "pad/Padclamp.c")
# The European SDK lies at 0x801D0000 and up. Lower addresses are hooked only by name: a fuzzy match
# down there named a game function after an SDK one (80148D00 "__OSSyncSram").
SDK_START = 0x801D0000
# SDK functions that are plain code and must run translated (static constructors, ...).
RECOMPILE_NAMES = ("__init_user", "__init_cpp", "__fini_cpp", "_ExitProcess")
# GX runs translated (it writes the FIFO that Source/gx feeds to the sms_gx core); only the functions that
# wait on GPU interrupts or read the GPU back keep a host body.
GX_KEEP = ("GXDrawDone", "GXSetDrawDone", "GXWaitDrawDone", "GXSetDrawSync", "GXReadDrawSync", "GXSetDrawSyncCallback",
           "GXSetDrawDoneCallback", "GXPeekZ", "GXPeekARGB", "GXPokeZ", "GXPokeARGB", "GXGetGPStatus", "GXGetFifoStatus",
           "GXReadGPMetric", "GXReadMemMetric", "GXReadPixMetric", "GXReadVCacheMetric", "GXClearGPMetric",
           "GXSetGPMetric", "GXAbortFrame", "__GXFinishInterruptHandler", "__GXTokenInterruptHandler",
           "GXGetCPUFifo", "GXGetGPFifo", "GXSetCPUFifo", "GXSetGPFifo", "GXInitFifoBase", "GXInitFifoPtrs",
           "GXGetFifoPtrs", "GXSaveCPUFifo", "GXEnableBreakPt", "GXDisableBreakPt", "GXSetBreakPtCallback",
           "__GXSaveCPUFifoAux", "__GXCleanGPFifo", "__GXFifoInit", "GXGetCurrentGXThread", "GXSetCurrentGXThread",
           "GXRedirectWriteGatherPipe", "GXRestoreWriteGatherPipe", "GXBeginDisplayList", "GXEndDisplayList", "__GXPEInit", "__GXInitRevisionBits")
LOW_HOOKS = ("__init_hardware", "__flush_cache", "__TRK_reset")


def main():
    names, out = sys.argv[1], sys.argv[2]
    rows = []
    seen = set()
    for line in open(names):
        if line.startswith("#") or not line.strip():
            continue
        addr, name, tu, kind = line.split()
        if tu == "-" or tu in RECOMPILE or not tu.startswith(HLE_PREFIXES):
            continue
        if tu.startswith("gx/") and name not in GX_KEEP:
            continue
        if name in RECOMPILE_NAMES:
            continue
        if int(addr, 16) < SDK_START and name not in LOW_HOOKS:
            continue
        if name in seen:
            continue  # same name twice (matcher): keep the first
        seen.add(name)
        rows.append((tu, name, addr, kind))
    with open(out, "w") as w:
        w.write("# Generated by Tools/recomp/make_hooks.py: SDK functions with host bodies (HLE).\n")
        w.write("# <name> <PAL address>  # <USA unit> <match kind>\n")
        for tu, name, addr, kind in sorted(rows):
            w.write("%-40s %s  # %s %s\n" % (name, addr, tu, kind))
        extra = os.path.join(os.path.dirname(out), "hooks_extra.txt")
        if os.path.exists(extra):
            w.write(open(extra).read())
    by = {}
    for tu, *_ in rows:
        k = tu.split("/")[0]
        by[k] = by.get(k, 0) + 1
    print("hooks:", len(rows), by)


if __name__ == "__main__":
    main()
